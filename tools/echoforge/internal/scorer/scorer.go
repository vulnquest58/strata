package scorer

import (
	"math"

	"github.com/echoforge/echoforge/internal/model"
	"github.com/echoforge/echoforge/internal/resolver"
)

// Weights defines the contribution of each signal to the confidence score.
const (
	WeightPassiveSource   = 30.0 // Any passive source hit (crt.sh, hackertarget, anubis, rapiddns...)
	WeightDNSResolves     = 25.0 // DNS A/AAAA record found
	WeightMultiResolver   = 10.0 // Multiple resolvers agree
	WeightHTTPSuccess     = 20.0 // HEAD request returns 2xx/3xx
	WeightTLSSAN          = 10.0 // TLS SAN/CN matches hostname
	WeightHighFreqPattern = 5.0  // High n-gram frequency token
	WeightEchoDepth       = 8.0  // Closer to seed = higher bonus (raised from 5→8)
	WeightEchoResolved    = 15.0 // Echo/Markov candidate that actually resolves (quality signal)
)

// isPassiveSource returns true if the source is a passive intelligence source
// (not generated by Markov/ngram/echo evolution).
func isPassiveSource(source string) bool {
	switch source {
	case "crt.sh", "otx", "wayback", "commoncrawl", "hackertarget", "anubis", "rapiddns":
		return true
	}
	return false
}

// isWordlistSource returns true if the source is a wordlist-based source.
func isWordlistSource(source string) bool {
	return source == "wordlist" || source == "wordlist-builtin"
}

// Scorer computes confidence scores for discovered subdomains.
type Scorer struct{}

// New creates a Scorer instance.
func New() *Scorer { return &Scorer{} }

// ScorePassive assigns a confidence score from passive harvesting data only.
// Used before DNS resolution.
func (s *Scorer) ScorePassive(source string, ngramFreq float64) float64 {
	score := 0.0

	if isPassiveSource(source) {
		score += WeightPassiveSource
	} else if isWordlistSource(source) {
		score += 5.0
	} else {
		// echo, markov, ngram — generated candidates
		score += 8.0
	}

	// N-gram frequency bonus (normalized 0–1)
	if ngramFreq > 0 {
		bonus := math.Min(ngramFreq, 1.0) * WeightHighFreqPattern
		score += bonus
	}

	return math.Min(score, 100.0)
}

// ScoreFull computes the final confidence score after all pipeline stages.
func (s *Scorer) ScoreFull(sub *model.Subdomain, res resolver.ResolutionResult, httpStatus int, tlsMatch bool, ngramFreq float64) float64 {
	score := 0.0

	// Passive source contribution
	if isPassiveSource(sub.Source) {
		score += WeightPassiveSource
	} else if isWordlistSource(sub.Source) {
		score += 5.0
	} else {
		// echo, markov, ngram — generated candidates
		score += 8.0
	}

	// DNS resolution
	if res.Resolves {
		score += WeightDNSResolves
		if res.AgreementCount >= 2 {
			score += WeightMultiResolver
		}

		// Extra bonus: echo/markov candidate that actually resolves is high-quality signal
		if !isPassiveSource(sub.Source) && !isWordlistSource(sub.Source) {
			score += WeightEchoResolved
		}
	}

	// HTTP verification
	if httpStatus >= 200 && httpStatus < 400 {
		score += WeightHTTPSuccess
	} else if httpStatus >= 400 && httpStatus < 500 {
		score += 5.0 // Still interesting (auth required, etc.)
	}

	// TLS SAN match
	if tlsMatch {
		score += WeightTLSSAN
	}

	// N-gram frequency bonus
	if ngramFreq > 0 {
		score += math.Min(ngramFreq, 1.0) * WeightHighFreqPattern
	}

	// Echo depth bonus (depth 0 = seed = max bonus, depth 1 = 80%, etc.)
	depthBonus := WeightEchoDepth * math.Max(0, 1.0-float64(sub.EchoDepth)*0.15)
	score += depthBonus

	return math.Min(math.Round(score*10)/10, 100.0)
}

// Category returns a human-readable confidence tier.
func Category(confidence float64) string {
	switch {
	case confidence >= 80:
		return "HIGH"
	case confidence >= 50:
		return "MEDIUM"
	case confidence >= 25:
		return "LOW"
	default:
		return "UNCERTAIN"
	}
}

// CategoryColor returns an ANSI color code for the confidence category.
func CategoryColor(confidence float64) string {
	switch {
	case confidence >= 80:
		return "\033[32m" // Green
	case confidence >= 50:
		return "\033[33m" // Yellow
	case confidence >= 25:
		return "\033[36m" // Cyan
	default:
		return "\033[90m" // Dark grey
	}
}

const Reset = "\033[0m"
